import {mkdirSync,writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
import {projectRoot} from './sites-env.mjs';
const runtime=path.join(projectRoot,'.sites-runtime');
mkdirSync(runtime,{recursive:true});
const config=path.join(runtime,'local-d1.json');
writeFileSync(config,JSON.stringify({name:'dukatrack-local',compatibility_date:'2026-05-15',d1_databases:[{binding:'DB',database_name:'site-creator-d1',database_id:'00000000-0000-4000-8000-000000000000',migrations_dir:path.join(projectRoot,'drizzle')}]},null,2));
const r=spawnSync(process.execPath,[path.join(projectRoot,'node_modules/wrangler/bin/wrangler.js'),'d1','migrations','apply','DB','--local','--config',config,'--persist-to',path.join(projectRoot,'.wrangler/state')],{stdio:'inherit',cwd:projectRoot});
if(r.error)throw r.error;
process.exit(r.status??1);
